export interface CountryRef {
  code: string;
  name: string;
  lat: number;
  lon: number;
}

const BY_CODE = new Map<string, CountryRef>(
  ROWS.map(([code, name, lat, lon]) => [code, { code, name, lat, lon }]),
);

/** Resolves an ISO alpha-2 code. Returns `null` for anything we cannot map. */
export function lookupCountry(code: string | null | undefined): CountryRef | null {
  if (!code) return null;
  return BY_CODE.get(code.trim().toUpperCase()) ?? null;
}
