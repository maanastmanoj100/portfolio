export function getRoleById(id: string): CareerRoleDefinition | undefined {
  return ROLES.find((r) => r.id === id);
}

export function getRolesByCategory(cat: RoleCategory): CareerRoleDefinition[] {
  return ROLES.filter((r) => r.category === cat);
}

export function getTotalEvidenceCount(role: CareerRoleDefinition): number {
  const ev = role.evidence;
  return ev.projects.length + ev.certifications.length + ev.labs.length + ev.skills.length + ev.blogPosts.length + ev.githubRepos.length;
}

export function getSkillGapSummary(role: CareerRoleDefinition): {
  demonstrated: number;
  inProgress: number;
  planned: number;
  notAddressed: number;
} {
  return {
    demonstrated: role.documentedCompetencies.length,
    inProgress: role.currentlyLearning.length,
    planned: role.futureGoals.length + role.suggestedProjects.length + role.recommendedCerts.length,
    notAddressed: role.suggestedLabs.length + role.suggestedReading.length,
  };
}
