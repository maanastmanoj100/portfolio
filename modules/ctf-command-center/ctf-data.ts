export function getChallengesByPlatform(platformId: string): CTFChallenge[] {
  return challenges.filter((c) => c.platform === platformId);
}

export function getChallengesByCategory(category: Category): CTFChallenge[] {
  return challenges.filter((c) => c.category === category);
}

export function getChallengesByDifficulty(difficulty: Difficulty): CTFChallenge[] {
  return challenges.filter((c) => c.difficulty === difficulty);
}

export function getChallengeById(id: string): CTFChallenge | undefined {
  return challenges.find((c) => c.id === id);
}

export function getCompletedChallenges(): CTFChallenge[] {
  return challenges.filter((c) => c.status === "completed");
}

export function getFavoriteChallenges(): CTFChallenge[] {
  return challenges.filter((c) => c.favorite);
}

